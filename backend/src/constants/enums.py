from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class CalibrationStatus(str, Enum):
    draft = 'draft'
    published = 'published'
    revoked = 'revoked'
class CredentialStatus(str, Enum):
    active = 'active'
    revoked = 'revoked'
class FollowStatus(str, Enum):
    certain = 'certain'
    pending = 'pending'
    excluded = 'excluded'
